"""Regenerate the self-hosted learning-UI web fonts.

Usage (fontTools + brotli required, e.g. in a virtualenv):
  python scripts/fonts/subset.py Jua-Regular.ttf Pretendard-Regular.woff2 Pretendard-SemiBold.woff2

Sources (both SIL OFL 1.1; licenses are copied into src/assets/fonts/). The subsets are
renamed "SignLingo Display" (from Jua) and "SignLingo Body" (from Pretendard):
  Jua         https://github.com/google/fonts/tree/main/ofl/jua
  Pretendard  https://github.com/orioncactus/pretendard (npm `pretendard`, dist/web/static/woff2)

Each face is split in two:
  core  ASCII, punctuation and every Hangul syllable used by the application source and
        published manifest. Every page downloads this file.
  ext   the remaining KS X 1001 Hangul syllables (2,350 in total). Browsers fetch it only
        when the page shows one of those characters, e.g. new expression text.
Syllables outside KS X 1001 fall back to the system font.
"""
import pathlib
import re
import sys

from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'src' / 'assets' / 'fonts'
CSS = ROOT / 'src' / 'design' / 'fonts.css'

BASE = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100)) | set(range(0x2010, 0x2028)) | set(range(0x2030, 0x205F)) \
    | set(range(0x2190, 0x219A)) | set(range(0x3000, 0x3040)) | {0x00B7, 0x2026, 0x00D7, 0x2715, 0x2713}
KSX = {c for c in range(0xAC00, 0xD7A4) if len(chr(c).encode('euc_kr', 'ignore')) == 2}


def used_syllables():
    text = ''
    for pattern in ('src/**/*.ts', 'src/**/*.tsx', 'src/**/*.css', 'src/**/*.json', 'public/content/*.json'):
        for file in ROOT.glob(pattern):
            text += file.read_text(encoding='utf-8')
    return {ord(c) for c in text if 0xAC00 <= ord(c) <= 0xD7A3}


def ranges(codes):
    codes = sorted(codes)
    out, start, prev = [], None, None
    for c in codes:
        if start is None:
            start = prev = c
        elif c == prev + 1:
            prev = c
        else:
            out.append((start, prev))
            start = prev = c
    if start is not None:
        out.append((start, prev))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def rename(font, family, style):
    """Modified Versions must not use a Reserved Font Name (OFL §3). Copyright and license
    records (name IDs 0, 13, 14) are kept unchanged."""
    for record in font['name'].names:
        value = {1: family, 16: family, 21: family, 2: style, 17: style, 22: style, 4: f'{family} {style}',
                 6: f'{family}-{style}'.replace(' ', ''), 3: f'{family} {style}; SignLingo subset'}.get(record.nameID)
        if value is not None:
            record.string = value


def build(source, name, codes, family, style):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True
    options.hinting = False
    font = subset.load_font(source, options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codes)
    subsetter.subset(font)
    rename(font, family, style)
    available = set(font.getBestCmap())
    target = OUT / f'{name}.woff2'
    subset.save_font(font, str(target), options)
    return available, target


def main(jua, regular, semibold):
    OUT.mkdir(parents=True, exist_ok=True)
    used = used_syllables()
    core, ext = BASE | used, KSX - used
    # Jua ships one heavy weight. Matching it for 400–800 lets headings use font-weight:700
    # (so contrast checkers classify them as bold) without synthesized faux bold.
    faces = [('SignLingo Display', jua, 'display', '400 800', 'Regular'),
             ('SignLingo Body', regular, 'body-regular', '400', 'Regular'),
             ('SignLingo Body', semibold, 'body-semibold', '600', 'SemiBold')]
    css = ['/* Generated by scripts/fonts/subset.py. Do not edit by hand. */']
    for family, source, stem, weight, style in faces:
        for part, codes in (('core', core), ('ext', ext)):
            available, target = build(source, f'{stem}-{part}', codes, family, style)
            css.append(
                f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weight};font-display:swap;"
                f"src:url('../assets/fonts/{target.name}') format('woff2');unicode-range:{ranges(available & codes)}}}")
            print(f'{target.name}: {target.stat().st_size // 1024} KiB, {len(available & codes)} code points')
    CSS.write_text('\n'.join(css) + '\n', encoding='utf-8')
    print(f'core Hangul syllables: {len(used)}')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
